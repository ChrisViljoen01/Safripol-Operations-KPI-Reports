  function toneOf(value, target) {
    if (nOrNull(value) === null || nOrNull(target) === null) return "";
    if (value <= target) return "good";
    return value <= target * 1.15 ? "warn" : "bad";
  }

  function toneNote(value, target, suffix) {
    if (nOrNull(value) === null || nOrNull(target) === null) return suffix;
    const diff = value - target;
    const sign = diff >= 0 ? "+" : "−";
    return `${sign}${Math.abs(diff).toFixed(2)} h ${suffix}`;
  }

